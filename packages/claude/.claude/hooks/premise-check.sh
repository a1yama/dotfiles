#!/bin/bash
# UserPromptSubmit フック: 「指示された手段を検証せずに実行する」のを着手前に止める。
#
# 狙いは2つの失敗。
#   1. 依頼に手段(どうやるか)が含まれていると、目的に対して最善かを検討せずそのまま実装する
#   2. 「間違っていたので直して」と言われると、前回選んだ手段そのものを疑わず、
#      言われた箇所だけ直す(対症療法)。同じ手戻りが何度も続く
# どちらもユーザー側からは「何も否定せずに従っているだけ」に見える。
#
# 起動判断をモデルに任せる設計は効かない。「立ち止まるべきだ」と気づく判断そのものが
# 追従圧に負けているのが本症状なので、トリガーだけは外部から機械的に引く
# (stop-frame-check.sh と同じ考え方)。ただし「その手段が妥当か」は意味論であり
# フックには判定できないため、判定はモデルに戻し、痕跡の有無だけを
# stop-premise-gate.sh が終了前に検査する。
#
# ここは deny できないイベントなので additionalContext による注入のみ。
# 実効性は Stop 側のゲートと対になって初めて出る。
#
# CLAUDE_PREMISE_CHECK_OFF=1 で無効化できる。
set -u

[ "${CLAUDE_PREMISE_CHECK_OFF:-}" = "1" ] && exit 0

input=$(cat)

prompt=$(printf '%s' "$input" | jq -r '.prompt // empty' 2>/dev/null)
[ -n "$prompt" ] || exit 0

# 判定はここだけに置く。stop-premise-gate.sh も同じ関数を source して使うため、
# 片方だけパターンを直して注入と検査がずれる事故を防ぐ
# shellcheck source=premise-signals.sh disable=SC1091
. "$(cd "$(dirname "$0")" && pwd)/premise-signals.sh"

signal=$(premise_signal "$prompt")
[ -n "$signal" ] || exit 0

# 以降のヒアテキストはモデルへ渡す文面。バッククォートは Markdown の記法であって
# コマンド置換ではないため展開させない(SC2016 は意図どおり)
# shellcheck disable=SC2016
if [ "$signal" = "rework" ]; then
  context='【前提チェック: 手戻りを検出】
直前の成果物が「間違っていた」と言われています。指示された修正にそのまま着手しないでください。

1. **その指摘自体が事実かを実物で確かめる。** 「間違っている」を前提に直し始めない。
   ユーザーの認識違い、別の原因、既に直っている、のいずれもあり得る。
   確認して食い違ったら「違います」と根拠を添えて言う。ただし**確認できたときだけ**言う。
   「違う気がする」で反論しない。逆張りは鵜呑みと同じだけ害がある。
2. 原因を特定する。症状ではなく原因。**前回選んだ手段そのものが原因ではないか**を最初に疑う。
3. 指示された修正が原因に対する打ち手かを判定する。対症療法なら、着手前にそう言う。
4. より良い手段があるなら、黙って従わず着手前に提示する。2〜4択になるなら AskUserQuestion。

最終応答に `⚖️ **前提**` 節を置き、3行で残す。
- 事実: <指摘が事実か。何を見て確認したか>
- 原因: <なぜそうなったか。前回の手段の選択ミスか、実装ミスか>
- 採否: <指示された修正が打ち手か。従うなら根拠、変えるなら代替案>

指示どおりで妥当なときも「妥当」と根拠付きで書く。無条件の追従は禁止。'
elif [ "$signal" = "target" ]; then
  context='【前提チェック: 数値目標を検出】
依頼に「満たすべき数字・条件」が入っています。求められているのは**その数字が成り立つ根拠**であって、
数字を形式的に満たした成果物ではありません。

指標を満たす最短経路は、たいてい目的を壊します。よくある抜け道:
- 「テストを通して」→ アサーションを緩める / モックで固めて実質何も検証しない
- 「ビルドを通して」→ 型を any にする / エラーを握りつぶす / 対象をコンパイル対象から外す
- 「3倍速くして」→ 測定条件でだけ速くする。実運用の入力では効かない
- 「カバレッジ80%」→ 実行するだけで何も検証しないテストを量産する
- 「この数値を出して」→ 条件を後から絞り込んで数字を合わせる。同じ条件でしか再現しない

着手前に検討する。
1. その数字は目的そのものか、代理指標か。背後にある狙いを言語化する。
2. 自分がこれから出す案が「数字だけ満たす抜け道」になっていないかを点検する。
3. 数字が成り立つ**範囲と条件**を示す。どこまでなら再現し、どこから崩れるのか。

満たせないなら「この条件では満たせない」と言い切り、代わりに何を見るべきかを出す。
数字を満たしただけの案を「できた」と報告しないでください。

最終応答に `⚖️ **前提**` 節を置き、3行で残す。
- 目的: <数字の背後にある狙い>
- 指定された数値: <その数字>が目的の代理として妥当か
- 採否: 数字が成り立つ根拠と適用範囲、または「満たせない/満たしても目的を外す」という判定'
else
  context='【前提チェック: 手段の指定を検出】
依頼に「どうやるか」が含まれています。目的には従い、手段は検証してから従ってください。

着手前に、指定された手段が目的に対して最善かを検討する。
より良い手段があるなら、黙って従わず着手前に提示する。2〜4択になるなら AskUserQuestion。

最終応答に `⚖️ **前提**` 節を置き、3行で残す。
- 目的: <指示の文面ではなく、達成したいこと>
- 指定された手段: <言われたやり方>が目的に対して最善か
- 採否: 従うなら根拠、変えるなら代替案

指示どおりで妥当なときも「妥当」と根拠付きで書く。無条件の追従は禁止。
ユーザーが方針を再確認したうえで同じ指示を繰り返した場合は、それが決定。そこからは従う。'
fi

jq -n --arg c "$context" \
  '{hookSpecificOutput:{hookEventName:"UserPromptSubmit",additionalContext:$c}}'
exit 0
